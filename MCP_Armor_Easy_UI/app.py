    def _show_splash(self):
        try:
            splash = LicenseSplash(self, self.hwid, self.expiry, self._accept_splash)
            self._license_splash = splash
            splash.update_idletasks()
            x = (self.winfo_screenwidth() - splash.winfo_width()) // 2
            y = (self.winfo_screenheight() - splash.winfo_height()) // 2
            splash.geometry('+%d+%d' % (max(0, x), max(0, y)))
            splash.lift(); splash.focus_force()
            threading.Thread(target=self._license_worker, daemon=True).start()
        except Exception:
            self._accept_splash()

    def _license_worker(self):
        code, expiry = _license_details()
        self.events.put(('license', code, expiry))

    def _accept_splash(self):
        for child in list(self.winfo_children()):
            if isinstance(child, tk.Toplevel):
                try: child.grab_release()
                except Exception: pass
                child.destroy()
