    def _launch_obf(self):
        if self.running: return False
        try:
            validate_paths(self.input_path.get(), self.output_path.get(), self.scope)
            os.makedirs(STATE_DIR, exist_ok=True)
            with open(RUN_CONFIG, 'w', encoding='utf-8') as handle: handle.write(self._build_config())
            # Source mode must not accidentally run an older packaged CLI.
            packaged = bool(getattr(sys, 'frozen', False) or '__compiled__' in globals())
            cli = _find_cli() if packaged else None
            if packaged and not cli: raise FileNotFoundError('CLI executable missing next to the UI')
            cwd = os.path.dirname(cli) if cli else ROOT_DIR
            argv = [cli, '--config', RUN_CONFIG] if cli else [sys.executable, '-m', 'MCP_Armor_Src', '--config', RUN_CONFIG]
            context = dict(output=self.output_path.get().strip(), log=bool(self.other['log_enabled']), env=os.environ.copy())
            if self.python27_path.get().strip(): context['env']['MCPARMOR_PY27'] = self.python27_path.get().strip()
            self.last_run_output = '$ ' + subprocess.list2cmdline(argv) + '\n'
            self._file_progress = None
            self.running = True
            self._set_status('状态：运行中' if self.language == '中文' else 'Status: Running')
            threading.Thread(target=self._worker, args=(argv, cwd, context), daemon=True).start()
            return True
        except Exception:
            self.running = False
            self.last_run_output = traceback.format_exc()
            messagebox.showerror(APP_TITLE, self.last_run_output, parent=self)
            return False

    def _worker(self, argv, cwd, context):
        # Only plain data crosses the thread boundary; no Tk variables or dialogs.
        chunks = ['$ ' + subprocess.list2cmdline(argv) + '\n']
        try:
            kwargs = dict(cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          env=context['env'], text=True, encoding='utf-8', errors='replace')
            if os.name == 'nt': kwargs['creationflags'] = subprocess.CREATE_NO_WINDOW
            with subprocess.Popen(argv, **kwargs) as proc:
                for line in proc.stdout:
                    chunks.append(line)
                    self.events.put(('log', line))
                    progress = parse_progress(line)
                    if progress is not None:
                        self.events.put(('progress', progress))
                code = proc.wait()
        except Exception:
            chunks.append(traceback.format_exc()); code = 1
        chunks.append('\nExit code: %s\n' % code)
        data = ''.join(chunks)
        if context['log']:
            try:
                os.makedirs(STATE_DIR, exist_ok=True)
                with open(RUN_LOG, 'w', encoding='utf-8') as handle: handle.write(data)
            except OSError as exc: data += '\nLog write error: %s' % exc
        self.events.put(('run', code, data, context['output']))

    def _poll_events(self):
        try:
            while True:
                self._accept_drop(self._drop_queue.get_nowait())
        except queue.Empty:
            pass
        try:
            while True:
                event = self.events.get_nowait()
                if event[0] == 'license':
                    _kind, self.hwid, self.expiry = event
                    splash = getattr(self, '_license_splash', None)
                    if splash is not None and splash.winfo_exists(): splash.set_expiry(self.expiry)
                elif event[0] == 'log':
                    self.last_run_output += event[1]
                elif event[0] == 'progress':
                    self._update_file_progress(event[1])
                elif event[0] == 'run':
                    _kind, code, data, artifact_root = event
                    self.running = False
                    self.last_run_output = data
                    if code == 0:
                        # The left pane is an artifact browser: once output is
                        # produced, show its renamed files/classes/functions.
                        if artifact_root and os.path.exists(artifact_root):
                            self._refresh_tree(artifact_root)
                        self._set_status('Status: Finished - showing output symbols')
                    else:
                        self._set_status('Status: Failed (%s) - Log' % code)
                        self.open_log()
                    callback = self._obf_done_callback
                    self._obf_done_callback = None
                    self._obf_cancel_callback = None
                    if callback: callback(code)
        except queue.Empty:
            pass
        self.after(100, self._poll_events)


