    def _build_config(self):
        s, other = self.settings, self.other
        ast_on = s['ast_level'] != 'off'
        byte_on = not other['no_bytecode_obf']
        mapped = byte_on and bool(other['opcode_replacement'])
        mcs = self.target_mode == 'netease'
        source = {key: ast_on and bool(s[key]) for key, _, _ in AST_CHECKS}
        source['module_rename'] = source['module_rename'] and self.scope == 'folder'
        source['function_split'] = source['function_split'] and self.scope == 'folder'
        source.update(project_analysis=ast_on, vm=False,
                      vm_ir=ast_on and bool(s['vm_ir']), vm_extension=ast_on and bool(s['vm_extension']))
        for key in s:
            if key.startswith('vm_') and key not in ('vm_ir', 'vm_extension'):
                source[key] = split_patterns(s[key]) if key in ('vm_include', 'vm_exclude') else s[key]
            if key.startswith('string_xor_') or key == 'string_split_parts': source[key] = s[key]
        if not ast_on or not (s['vm_ir'] or s['vm_extension']): source['vm_ratio'] = 0
        source['module_rename_exclude'] = split_patterns(other['module_rename_exclude'])
        source['ast_exclude'] = split_patterns(other['ast_exclude'])
        bytecode = {key: byte_on and bool(s[key]) for key, _, _ in BYTE_CHECKS + ADVANCED_BYTE_CHECKS}
        bytecode.update(enabled=byte_on, flow=byte_on, flow_ratio=s['flow_ratio'], flow_max_edges=s['flow_max_edges'],
                        opcode_replacement=mapped, opcode_runtime='mcs' if mcs else 'std',
                        mcs_opmap_version=other['mcs_opmap_version'] if mcs else 0,
                        code_tuple_payload=bool(s.get('code_tuple_payload', other.get('code_tuple_payload', True))), source_only=split_patterns(other['source_only']))
        # The compact cpickle preset forces MCS mapping in the existing core.
        # Use the CodeTuple/cPickle function loader when mapping is disabled or STD is selected.
        loader = other.get('loader_mode', 'cpickle')
        payload = bool(s.get('code_tuple_payload', other.get('code_tuple_payload', True)))
        sections = [('project', [('input', self.input_path.get()), ('output', self.output_path.get()),
                    ('folder', self.scope == 'folder'), ('include', ['*.py']), ('exclude', split_patterns(other['exclude'])),
                    ('clean_output', other['clean_output'])]),
                    ('source', list(source.items())), ('bytecode', list(bytecode.items()))]
        # Top-level keys match the CLI aliases exactly; unknown nested aliases used to disappear silently.
        top = dict(preset='none', resource_profile={'extended': 'strong'}.get(self.volume_level, self.volume_level),
                   loader_mode=loader, loader_dialect=other.get('loader_dialect', 'auto'),
                   loader_vm=other.get('loader_vm', False), code_tuple_payload=payload,
                   output_date=other['output_date'], debug=other['debug'],
                   static_check=True, python27=self.python27_path.get().strip() or None,
                   anti_debug=other.get('anti_debug', False), key_len=16,
                   write_rename_mapping=other['write_rename_mapping'],
                   netease_profile='none', fix_netease_register=mcs)
        return _yaml(sections) + ''.join('%s: %s\n' % (key, 'null' if value is None else _scalar(value)) for key, value in top.items())

