    def _enable_native_drop(self):
        """Enable Explorer file/folder drops without a third-party Tk DLL."""
        if os.name != 'nt':
            return
        try:
            self._drop_procs = []
            shell32 = ctypes.windll.shell32
            user32 = ctypes.windll.user32
            ptr = ctypes.c_void_p
            shell32.DragAcceptFiles.argtypes = [wintypes.HWND, wintypes.BOOL]
            shell32.DragAcceptFiles.restype = None
            shell32.DragQueryFileW.argtypes = [wintypes.HANDLE, wintypes.UINT, wintypes.LPWSTR, wintypes.UINT]
            shell32.DragQueryFileW.restype = ctypes.c_uint
            shell32.DragFinish.argtypes = [wintypes.HANDLE]
            shell32.DragFinish.restype = None
            user32.GetWindowLongPtrW.argtypes = [wintypes.HWND, ctypes.c_int]
            user32.GetWindowLongPtrW.restype = ctypes.c_void_p
            user32.SetWindowLongPtrW.argtypes = [wintypes.HWND, ctypes.c_int, ctypes.c_void_p]
            user32.SetWindowLongPtrW.restype = ctypes.c_void_p
            user32.CallWindowProcW.argtypes = [ctypes.c_void_p, wintypes.HWND,
                                                wintypes.UINT, wintypes.WPARAM, wintypes.LPARAM]
            user32.CallWindowProcW.restype = ctypes.c_ssize_t
            wndproc_type = ctypes.WINFUNCTYPE(ctypes.c_ssize_t, wintypes.HWND,
                                               wintypes.UINT, wintypes.WPARAM, wintypes.LPARAM)
            def install(widget):
                hwnd = widget.winfo_id()
                shell32.DragAcceptFiles(hwnd, True)
                old_proc = user32.GetWindowLongPtrW(hwnd, -4)

                def wndproc(window, message, wparam, lparam):
                    if message == 0x0233:
                        try:
                            count = shell32.DragQueryFileW(wparam, 0xFFFFFFFF, None, 0)
                            for index in range(count):
                                buf = ctypes.create_unicode_buffer(32768)
                                shell32.DragQueryFileW(wparam, index, buf, len(buf))
                                if buf.value: self._drop_queue.put(buf.value)
                        except Exception:
                            self.events.put(('log', traceback.format_exc()))
                        finally: shell32.DragFinish(wparam)
                        return 0
                    return user32.CallWindowProcW(old_proc, window, message, wparam, lparam)

                callback = wndproc_type(wndproc)
                user32.SetWindowLongPtrW(hwnd, -4, ctypes.cast(callback, ctypes.c_void_p))
                self._drop_procs.append((hwnd, old_proc, callback))

            # Explorer sends WM_DROPFILES to the child window under the
            # pointer, so register both the top-level and the centre target.
            install(self)
            if hasattr(self, 'drop'):
                install(self.drop)
                for child in self.drop.winfo_children(): install(child)
        except Exception:
            self.events.put(('log', traceback.format_exc()))

    def _accept_drop(self, path):
        path = os.path.abspath(path)
        if not (os.path.isfile(path) or os.path.isdir(path)):
            return
        if os.path.isfile(path) and not path.lower().endswith(PY_EXTENSIONS):
            self._set_status(self._t('drop_bad'))
            return
        self.input_path.set(path)
        self.scope = 'file' if os.path.isfile(path) else 'folder'
        self._refresh_tree(path)
        self._set_status(self._t('dropped'))

    def _set_status(self, value):
        self.status.set(value)

    def _update_file_progress(self, event):
        """Render the worker's current file as ``13/81 py:name.py``."""
        self._file_progress = event
        zh = self.language == '中文'
        prefix = '状态' if zh else 'Status'
        state = event.get('state')
        verb = {'start': '混淆中' if zh else 'Obfuscating',
                'done': '已完成' if zh else 'Processed',
                'error': '混淆失败' if zh else 'Failed'}.get(state, state)
        self._set_status('%s: %s %d/%d  py:%s' % (
            prefix, verb, event['index'], event['total'], event['path']))

    def _progress_failure_status(self, code):
        event = getattr(self, '_file_progress', None)
        prefix = '状态' if self.language == '中文' else 'Status'
        if event is not None and event.get('state') in ('start', 'error'):
            return '%s: %s (%s) %d/%d  py:%s - Log' % (
                prefix, '混淆失败' if self.language == '中文' else 'Failed',
                code, event['index'], event['total'], event['path'])
        return '%s: %s (%s) - Log' % (
            prefix, '失败' if self.language == '中文' else 'Failed', code)

    def _tree_select(self, _event=None):
        sel = self.tree.selection()
        if sel:
            values = self.tree.item(sel[0], 'values')
            if values: self._set_status('Status: ' + values[0])

    def _python_symbols(self, path):
        """Read top-level classes/functions for the ZKM-like file tree."""
        text = ''
        try:
            with open(path, 'rb') as handle:
                text = handle.read().decode('utf-8-sig', 'replace')
            module = ast.parse(text, path)
            result = []
            for node in module.body:
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                    kind = 'class' if isinstance(node, ast.ClassDef) else 'function'
                    result.append((kind, node.name))
            return result
        except Exception:
            return [('function' if match.group(1) == 'def' else 'class', match.group(2))
                    for match in re.finditer(r'^\s*(def|class)\s+([A-Za-z_][A-Za-z0-9_]*)', text, re.M)]

    def _add_python_node(self, parent, path):
        node = self.tree.insert(parent, 'end', text=os.path.basename(path), values=(path,))
        if path.lower().endswith('.py'):
            for kind, name in self._python_symbols(path):
                self.tree.insert(node, 'end', text='%s: %s' % (kind, name), values=(path,))

    def _folder_has_python(self, path):
        try:
            return any(name.lower().endswith(PY_EXTENSIONS)
                       for _base, _dirs, files in os.walk(path)
                       for name in files)
        except OSError:
            return False

    def _insert_folder(self, parent, path):
        try:
            entries = sorted(os.listdir(path), key=lambda x: (not os.path.isdir(os.path.join(path, x)), x.lower()))
        except OSError:
            return
        for name in entries:
            child = os.path.join(path, name)
            if os.path.isdir(child):
                if self._folder_has_python(child):
                    branch = self.tree.insert(parent, 'end', text=name, values=(child,), open=True)
                    self._insert_folder(branch, child)
            elif name.lower().endswith(PY_EXTENSIONS):
                self._add_python_node(parent, child)

    def _refresh_tree(self, path):
        if not hasattr(self, 'tree'): return
        self.tree.delete(*self.tree.get_children())
        if os.path.isfile(path):
            self._add_python_node('', path); return
        root = self.tree.insert('', 'end', text=os.path.basename(path) or path, values=(path,), open=True)
        self._insert_folder(root, path)

