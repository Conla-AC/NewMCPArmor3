    @staticmethod
    def _merge_loaded_values(target, values):
        """Apply only known setting keys and coerce scalar types."""
        if not isinstance(values, dict):
            return
        for key in list(target):
            if key not in values:
                continue
            value = values[key]
            current = target[key]
            if isinstance(current, bool):
                value = _config_bool(value, current)
            elif isinstance(current, int) and not isinstance(current, bool):
                try:
                    value = int(value)
                except (TypeError, ValueError):
                    continue
            elif isinstance(current, str):
                if isinstance(value, (list, tuple)):
                    value = '; '.join(str(item) for item in value)
                else:
                    value = str(value)
            target[key] = value

    def _apply_config_snapshot(self, data):
        """Load an EasyUI snapshot or a regular CLI YAML configuration."""
        if not isinstance(data, dict):
            raise ValueError('配置文件必须是对象 / Config must be an object')
        state = data if data.get('schema') == CONFIG_SCHEMA else data.get('easyui_state')
        if isinstance(state, dict):
            settings = data.get('settings', data.get('easyui_settings', {}))
            other = data.get('other', data.get('easyui_other', {}))
            self._merge_loaded_values(self.settings, settings)
            self._merge_loaded_values(self.other, other)
            input_path = state.get('input_path', self.input_path.get())
            output_path = state.get('output_path', self.output_path.get())
            scope = state.get('scope', self.scope)
            language = state.get('language', self.language)
            volume = state.get('volume_level', self.volume_level)
            target = state.get('target_mode', self.target_mode)
            python27 = state.get('python27_path', self.python27_path.get())
        else:
            # Accept configs produced by the CLI or older EasyUI versions.
            project = data.get('project', {}) or {}
            basic = data.get('basic', {}) or {}
            source = data.get('source', {}) or {}
            bytecode = data.get('bytecode', {}) or {}
            top = data
            self._merge_loaded_values(self.settings, source)
            self._merge_loaded_values(self.settings, bytecode)
            self._merge_loaded_values(self.other, basic)
            self._merge_loaded_values(self.other, top)
            for key in ('loader_mode', 'loader_dialect', 'loader_vm',
                        'code_tuple_payload', 'code_tuple_field_shuffle',
                        'code_tuple_fragments', 'code_tuple_provider_graph',
                        'code_field_descriptors', 'code_fused_restore',
                        'loader_reference_cleanup', 'code_capsule_proxy',
                        'index_pool_shuffle', 'delayed_const_access'):
                if key in top:
                    if key in self.settings:
                        self.settings[key] = _config_bool(top[key])
                    else:
                        self.other[key] = top[key]
            input_path = project.get('input', top.get('input', self.input_path.get()))
            output_path = project.get('output', top.get('output', self.output_path.get()))
            scope = 'folder' if _config_bool(project.get('folder', top.get('folder', self.scope == 'folder'))) else 'file'
            language = self.language
            volume = top.get('resource_profile', self.volume_level)
            target = 'netease' if str(top.get('opcode_runtime', 'mcs')).lower() == 'mcs' else 'native'
            python27 = top.get('python27', (data.get('runtime', {}) or {}).get('python27', self.python27_path.get()))
        self.input_path.set(str(input_path or ''))
        self.output_path.set(str(output_path or ''))
        self.python27_path.set(str(python27 or ''))
        self.scope = 'file' if scope == 'file' else 'folder'
        if language in ('中文', 'English'):
            self.language = language
        if volume == 'extended':
            volume = 'strong'
        if volume in ('compact', 'balanced', 'strong', 'unlimited'):
            self.volume_level = volume
        if target in ('netease', 'native'):
            self.target_mode = target
        # Use __dict__ here rather than hasattr(): a headless/test instance
        # created before Tk initialization would route hasattr through
        # Tk.Misc.__getattr__ recursively.
        if self.__dict__.get('tree') is not None and self.input_path.get():
            self._refresh_tree(self.input_path.get())
        self._apply_language()

    def save_config(self):
        """Save an exact EasyUI snapshot, optionally as CLI-readable YAML."""
        path = filedialog.asksaveasfilename(
            parent=self, title='保存 MCPArmor 配置 / Save configuration',
            initialdir=STATE_DIR, initialfile='mcparmor_profile.json',
            defaultextension='.json',
            filetypes=[('MCPArmor JSON', '*.json'),
                       ('MCPArmor YAML', '*.yml *.yaml'),
                       ('All files', '*.*')])
        if not path:
            return
        try:
            if not os.path.isdir(os.path.dirname(os.path.abspath(path))):
                os.makedirs(os.path.dirname(os.path.abspath(path)))
            payload = self._capture_config()
            if os.path.splitext(path)[1].lower() in ('.yml', '.yaml'):
                content = self._build_config() + '\n' + _config_yaml_state(payload)
            else:
                payload['cli_config'] = self._build_config()
                content = json.dumps(payload, ensure_ascii=False, indent=2,
                                     sort_keys=True)
            temp = path + '.tmp'
            with open(temp, 'w', encoding='utf-8', newline='') as handle:
                handle.write(content)
            os.replace(temp, path)
            self._set_status(('状态：配置已保存 ' if self.language == '中文' else 'Status: Config saved ') + os.path.basename(path))
        except Exception as exc:
            try:
                if os.path.isfile(path + '.tmp'):
                    os.remove(path + '.tmp')
            except Exception:
                pass
            messagebox.showerror(APP_TITLE, str(exc), parent=self)

