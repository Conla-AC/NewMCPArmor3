def validate_paths(src, dst, scope):
    if not src.strip() or not dst.strip(): raise ValueError('输入和输出均需填写 / Input and output required')
    a, b = (os.path.normcase(os.path.realpath(value.strip())) for value in (src, dst))
    if not os.path.exists(a): raise ValueError('输入不存在 / Input does not exist')
    if a == b: raise ValueError('输出与输入相同 / Output equals input')
    try: common = os.path.commonpath([a, b])
    except ValueError: common = None
    if scope == 'folder' and common in (a, b):
        raise ValueError('输入输出目录应相互独立 / Input and output directories must not overlap')
    if scope == 'file' and os.path.isdir(b): raise ValueError('单文件模式需要输出文件名 / Output filename required')
    return True


